import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import JSZip from 'jszip';
const manifest=JSON.parse(await fs.readFile('extension.json','utf8'));
const file=`build/dist/${manifest.name}_v${manifest.version}.eext`;
const zip=await JSZip.loadAsync(await fs.readFile(file),{checkCRC32:true});
const html=await zip.file('iframe/index.html').async('string');
const main=await zip.file('dist/index.js').async('string');
assert.ok(html.includes('<style>')&&!html.includes('src="/iframe/app.js"'));
assert.ok(html.includes('document.body.dataset.started')&&html.includes('track-length-command-v1'));
assert.ok(html.includes('id="mode"')&&html.includes('自动推挤')&&html.includes('仅空位补长'));
assert.ok(html.includes('id="pattern"')&&html.includes('单边蛇形')&&html.includes('双边蛇形')&&html.includes('大折返')&&html.includes('id="lobes"'));
assert.ok(html.includes('id="minAmplitude"')&&html.includes('间距 W')&&html.includes('最小振幅 H'));
assert.ok(html.includes('value="mixed"')&&html.includes('混合模式')&&main.includes('fitMixedSteps'));
assert.ok(html.includes('id="dynamicAmplitude"')&&html.includes('动态振幅')&&main.includes('fitAdaptiveLineSteps'));
assert.ok(html.includes('id="clear"')&&html.includes('自动识别')&&main.includes('getAdjacentPrimitives')&&main.includes('crossLayerRoutes'));
assert.ok(html.includes('id="groupKind"')&&html.includes('id="targetGroup"')&&html.includes('等长网络组')&&html.includes('网络类')&&main.includes('getAllEqualLengthNetGroups')&&main.includes('getAllNetClasses')&&main.includes('createPadPriority'));
assert.ok(html.includes('getCurrentTheme')&&html.includes('prefers-color-scheme:dark')&&html.includes('var(--trace-')&&html.includes('data-theme="dark"'));
for(const m of html.matchAll(/<script>([\s\S]*?)<\/script>/g))new vm.Script(m[1]);
new vm.Script(main);
assert.ok(main.includes('openPanel')&&main.includes('track-length-journal-v1'));
assert.ok(main.includes('shoveLengthsSteps')&&main.includes('resolvePlansSteps'));
assert.ok(!main.includes('route-spacing')&&!main.includes('console.log('));
assert.ok(!Object.keys(zip.files).some(p=>/^(tests|src|validation|node_modules|scripts)\//.test(p)));
const ids=manifest.headerMenus.pcb.flatMap(m=>[m.id,...m.menuItems.map(i=>i.id)]);
assert.equal(ids.length,new Set(ids).size);
for(const lang of ['en','zh-Hans']){const locale=JSON.parse(await zip.file(`locales/extensionJson/${lang}.json`).async('string'));for(const m of manifest.headerMenus.pcb){assert.ok(locale[m.title]);for(const item of m.menuItems)assert.ok(locale[item.title]);}}
const report={file,version:manifest.version,crcPassed:true,scriptsParsed:true,menusUnique:true,htmlBytes:Buffer.byteLength(html),mainBytes:Buffer.byteLength(main),packageBytes:(await fs.stat(file)).size};
await fs.mkdir('validation',{recursive:true});await fs.writeFile('validation/package.json',JSON.stringify(report,null,2));console.info(report);
